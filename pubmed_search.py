"""
PubMed Search Script
Searches PubMed for 'medical waste AND hospital' and saves results to Excel.

Requirements: pip install requests openpyxl
"""

import subprocess
import sys

def install(package):
    subprocess.check_call([sys.executable, "-m", "pip", "install", package, "-q"],
                          timeout=120)

for pkg in ["requests", "openpyxl"]:
    try:
        install(pkg)
    except Exception as e:
        print(f"Warning: could not install {pkg}: {e}")

import requests
import openpyxl
import xml.etree.ElementTree as ET
from datetime import datetime
import time

BASE_URL = "https://eutils.ncbi.nlm.nih.gov/entrez/eutils"
HEADERS = {
    "User-Agent": "Mozilla/5.0 (compatible; PubMedScript/1.0; mailto:researcher@example.com)"
}
PARAMS_BASE = {
    "tool": "pubmed_research_script",
    "email": "researcher@example.com",
}

QUERY = "medical waste AND hospital"
MAX_RESULTS = 100


def fetch_pubmed_articles():
    """Fetch articles from PubMed via NCBI E-utilities."""
    print(f"Searching PubMed for: {QUERY}")

    search_resp = requests.get(
        f"{BASE_URL}/esearch.fcgi",
        headers=HEADERS,
        params={**PARAMS_BASE, "db": "pubmed", "term": QUERY,
                "retmax": MAX_RESULTS, "retmode": "xml"},
        timeout=30,
    )
    search_resp.raise_for_status()

    search_root = ET.fromstring(search_resp.text)
    ids = [el.text for el in search_root.findall(".//IdList/Id")]
    print(f"Found {len(ids)} article IDs")

    if not ids:
        return []

    time.sleep(0.4)

    fetch_resp = requests.get(
        f"{BASE_URL}/efetch.fcgi",
        headers=HEADERS,
        params={**PARAMS_BASE, "db": "pubmed", "id": ",".join(ids),
                "rettype": "xml", "retmode": "xml"},
        timeout=60,
    )
    fetch_resp.raise_for_status()

    fetch_root = ET.fromstring(fetch_resp.text)
    raw_articles = fetch_root.findall(".//PubmedArticle")
    print(f"Processing {len(raw_articles)} articles...")

    results = []
    for article in raw_articles:
        try:
            title_el = article.find(".//ArticleTitle")
            title = "".join(title_el.itertext()) if title_el is not None else "N/A"

            authors = []
            for author in article.findall(".//AuthorList/Author"):
                last = author.findtext("LastName", "")
                fore = author.findtext("ForeName", "")
                if last:
                    authors.append(f"{last} {fore}".strip())
            authors_str = "; ".join(authors) if authors else "N/A"

            year = (article.findtext(".//PubDate/Year")
                    or article.findtext(".//PubDate/MedlineDate", "N/A"))
            year = year[:4] if year and len(year) > 4 else year

            abstract_parts = article.findall(".//AbstractText")
            abstract = " ".join("".join(el.itertext()) for el in abstract_parts) \
                if abstract_parts else "N/A"

            pmid = article.findtext(".//MedlineCitation/PMID", "")
            link = f"https://pubmed.ncbi.nlm.nih.gov/{pmid}/" if pmid else "N/A"

            results.append((title, authors_str, year, abstract, link))
        except Exception as e:
            print(f"  Skipping article: {e}")

    return results



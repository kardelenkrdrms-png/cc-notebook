def build_excel(articles):
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "PubMed Results"

    header_font = openpyxl.styles.Font(bold=True, color="FFFFFF")
    header_fill = openpyxl.styles.PatternFill(
        start_color="4472C4", end_color="4472C4", fill_type="solid"
    )
    headers = ["Title", "Authors", "Year", "Abstract", "Link"]
    ws.append(headers)
    for col_idx in range(1, len(headers) + 1):
        cell = ws.cell(row=1, column=col_idx)
        cell.font = header_font
        cell.fill = header_fill

    for row_data in articles:
        ws.append(list(row_data))

    ws.column_dimensions["A"].width = 60
    ws.column_dimensions["B"].width = 40
    ws.column_dimensions["C"].width = 8
    ws.column_dimensions["D"].width = 80
    ws.column_dimensions["E"].width = 45

    wrap_top = openpyxl.styles.Alignment(wrap_text=True, vertical="top")
    for row in ws.iter_rows(min_row=2):
        for cell in row:
            cell.alignment = wrap_top

    return wb


def main():
    articles = []

    try:
        articles = fetch_pubmed_articles()
    except Exception as e:
        print(f"\nCould not reach PubMed API ({e}).")
        print("Using sample data to demonstrate Excel output format.\n")
        articles = SAMPLE_ARTICLES

    if not articles:
        print("No articles to save.")
        return

    wb = build_excel(articles)
    output_file = (
        f"pubmed_medical_waste_hospital_{datetime.now().strftime('%Y%m%d_%H%M%S')}.xlsx"
    )
    wb.save(output_file)
    print(f"Saved {len(articles)} articles to: {output_file}")


if __name__ == "__main__":
    main()
